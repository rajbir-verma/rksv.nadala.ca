$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$data = Get-Content (Join-Path $root 'data/resume.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$utf8 = [System.Text.UTF8Encoding]::new($false)

function Format-Html([string]$value) {
    [System.Net.WebUtility]::HtmlEncode($value)
}

function Set-GeneratedSection([string]$html, [string]$section, [string]$content) {
    $start = "<!-- generated:$section -->"
    $end = "<!-- /generated:$section -->"
    $pattern = '(?s)' + [regex]::Escape($start) + '.*?' + [regex]::Escape($end)
    if ([regex]::Matches($html, $pattern).Count -ne 1) {
        throw "Expected one generated block for $section in index.html."
    }
    [regex]::Replace($html, $pattern, { param($match) "$start`n$content`n        $end" })
}

$summary = ($data.summary | ForEach-Object { "<p>$(Format-Html $_)</p>" }) -join "`n"
$features = foreach ($job in $data.experience) {
    foreach ($item in $job.accomplishments | Where-Object title) {
        $title = if ($item.portfolioTitle) { $item.portfolioTitle } else { $item.title }
        $text = if ($item.portfolioText) { $item.portfolioText } else { $item.text }
        $tags = ($item.tags | ForEach-Object { "<span>$(Format-Html $_)</span>" }) -join ''
        "<article class='feature'><h3>$(Format-Html $title)</h3><p>$(Format-Html $text)</p><div class='tags'>$tags</div></article>"
    }
}
$timeline = foreach ($job in $data.experience) {
    $lead = ($job.accomplishments | Where-Object { -not $_.title } | Select-Object -First 2 | ForEach-Object { Format-Html $_.text }) -join ' '
    if ($job.portfolioSummary) { $lead = Format-Html $job.portfolioSummary }
    @"
<article class="job">
  <div class="job-meta"><span class="job-date">$(Format-Html $job.dates)</span><span class="job-company">$(Format-Html $job.company)</span></div>
  <div><h3>$(Format-Html $job.role)</h3><p>$lead</p></div>
</article>
"@
}
$portfolioSkills = foreach ($group in $data.skills) {
    $items = ($group.items | ForEach-Object { Format-Html $_ }) -join ' &middot; '
    "<div><h3>$(Format-Html $group.title)</h3><p>$items</p></div>"
}

$indexPath = Join-Path $root 'index.html'
$index = [IO.File]::ReadAllText($indexPath)
$portfolioSummary = if ($data.portfolioSummary) { ($data.portfolioSummary | ForEach-Object { "<p>$(Format-Html $_)</p>" }) -join "`n" } else { $summary }
$index = Set-GeneratedSection $index 'summary' $portfolioSummary
$index = Set-GeneratedSection $index 'highlights' ($features -join "`n")
$index = Set-GeneratedSection $index 'experience' ($timeline -join "`n")
$index = Set-GeneratedSection $index 'skills' ($portfolioSkills -join "`n")

$name = Format-Html $data.name
$role = Format-Html $data.role
$email = Format-Html $data.email
$website = Format-Html $data.website
$websiteLabel = Format-Html ([uri]$data.website).Host
$github = Format-Html $data.github
$githubLabel = Format-Html ($data.github -replace '^https://')
$resumeSkills = foreach ($group in $data.skills) {
    "<li><strong>$(Format-Html $group.title)</strong> &ndash; $(Format-Html ($group.items -join ', '))</li>"
}
$resumeJobs = foreach ($job in $data.experience) {
    $bullets = ($job.accomplishments | ForEach-Object { "        <li>$(Format-Html $_.text)</li>" }) -join "`n"
    @"
    <article>
      <h3>$(Format-Html $job.role) &mdash; $(Format-Html $job.company)</h3>
      <p class="dates">$(Format-Html $job.dates)</p>
      <ul>
$bullets
      </ul>
    </article>
"@
}

$resume = @"
<!doctype html>
<!-- Generated by scripts/build.ps1 from data/resume.json. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Resume of $name, $role.">
  <title>Rajbir_Karan_Verma_Resume</title>
  <link rel="icon" type="image/svg+xml" href="../favicon.svg">
  <link rel="stylesheet" href="resume.css">
  <script src="print.js" defer></script>
</head>
<body>
  <nav class="controls" aria-label="Resume controls">
    <a href="../">&larr; RKSV Portfolio</a>
    <button type="button" id="print-resume" hidden>Save as PDF</button>
  </nav>
  <main>
    <header>
      <h1>$name</h1>
      <p class="role">$role</p>
      <p class="contact"><a href="mailto:$email">$email</a><a href="$website">$websiteLabel</a><a href="$github">$githubLabel</a></p>
    </header>
    <section>
      <h2>Professional Summary</h2>
      $summary
    </section>
    <section>
      <h2>Professional Experience</h2>
$($resumeJobs -join "`n")
    </section>
    <section>
      <h2>Technical Skills</h2>
      <ul class="skills">
        $($resumeSkills -join "`n        ")
      </ul>
    </section>
  </main>
</body>
</html>
"@

[IO.File]::WriteAllText($indexPath, $index, $utf8)
[IO.File]::WriteAllText((Join-Path $root 'resume/index.html'), "$resume`n", $utf8)
